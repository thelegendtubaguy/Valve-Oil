#!/usr/bin/env python3
"""Regenerate installer/klipper/tltg/filament_catalog.py.

Maintainer tool. It builds QIDI filament-database entries for Anycubic and
Elegoo filaments from the vendors' slicer profiles (OrcaSlicer's Anycubic
profiles, ElegooSlicer's Elegoo profiles) and QIDI's stock 0.4 mm database:

- names, material types, and nozzle temperature ranges come from each
  vendor's profiles (the range of the variant that reaches highest);
- the remaining QIDI fields (Box heater range, chamber, drying) come from the
  QIDI entry for the same kind of material;
- IDs are ``QFX`` (Anycubic) and ``QFY`` (Elegoo) plus two digits. An ID
  already in the catalog is never changed, because tags carry it.

Usage:
  generate_filament_catalog.py --orca-profiles <OrcaSlicer>/resources/profiles \\
      --elegoo-profiles <ElegooSlicer>/resources/profiles \\
      --qidi-database <filament_config>/filament-0.4.json
"""
from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "installer/klipper/tltg/filament_catalog.py"
HEADER = ("# Anycubic and Elegoo filaments for QIDI's filament database, and Elegoo tag codes.\n"
          "# Generated by scripts/generate_filament_catalog.py; do not edit.\n"
          "import json\n\nCATALOG = json.loads(r\"\"\"\n")
FOOTER = '"""\n)\n'


def read_catalog() -> dict:
    if not OUTPUT.is_file():
        return {"filaments": {}}
    text = OUTPUT.read_text(encoding="utf-8")
    return json.loads(text[text.index('r"""') + 4:text.rindex('"""')])
NOZZLES = ("0.2", "0.4", "0.6", "0.8")
BRANDS = {"Anycubic": "X", "Elegoo": "Y"}
SKIP = {"Anycubic PLA Slik"}  # misspelled duplicate of Anycubic PLA Silk in OrcaSlicer

# QIDI 0.2 mm omits filled, particle, silk, and flexible filaments; 0.8 mm omits silk and PEBA.
NOT_02 = re.compile(r"CF|GF|Wood|Metal|Marble|Galaxy|Sparkle|Glow|Luminous|Silk|TPU|PEBA|PAHT|\bPA\b", re.I)
NOT_08 = re.compile(r"Silk|PEBA", re.I)

# QIDI entry whose Box, chamber, and drying fields fit each material (first match wins).
TEMPLATES = [
    (r"PLA-CF", "QIDI PLA-CF"), (r"PLA.*Wood", "QIDI WOOD Rapido"), (r"PLA.*Silk", "Generic PLA Silk"),
    (r"PLA", "Generic PLA"), (r"PVA", "Generic PLA"),
    (r"PETG-CF", "QIDI PETG-CF"), (r"PETG-GF", "QIDI PETG-GF"), (r"PET-CF", "QIDI PET-CF"), (r"PETG", "Generic PETG"),
    (r"ASA-CF", "QIDI ASA-CF20 Core"), (r"ASA", "QIDI ASA"), (r"ABS", "Generic ABS"),
    (r"PC-FR", "QIDI PC/ABS-FR"), (r"PC", "Generic PC"),
    (r"PA6-CF", "QIDI PA6-CF"), (r"PAHT-CF", "QIDI PAHT-CF"), (r"PAHT|PA\b", "QIDI UltraPA"),
    (r"PEBA", "QIDI PEBA 95A"), (r"TPU", "Generic TPU 95A"),
]
# QIDI type strings for materials QIDI's own entries do not name.
TYPES = [(r"PLA-CF", "PLA-CF"), (r"PVA", "PVA"), (r"PLA", "PLA"), (r"PETG-CF", "PETG-CF"), (r"PETG-GF", "PETG-GF"),
         (r"PET-CF", "PET-CF"), (r"PETG", "PETG"), (r"ASA-CF", "ASA-CF"), (r"ASA", "ASA"), (r"ABS", "ABS"),
         (r"PC-FR", "PC-FR"), (r"PC-CF", "PC-CF"), (r"PC-GF", "PC-GF"), (r"PC", "PC"), (r"PA6-CF", "PA6-CF"),
         (r"PAHT-CF", "PAHT-CF"), (r"PAHT", "PAHT"), (r"PA\b", "PA"), (r"PEBA", "PEBA"), (r"TPU", "TPU")]

# Elegoo tag codes (Savion/elegoo-rfid-editor src/lib/materials.ts, MIT) mapped to ElegooSlicer names.
ELEGOO_MATERIALS = {"00807665": "PLA", "80698471": "PETG", "00656683": "ABS", "00848085": "TPU", "00008065": "PA",
                    "00678069": "CPE", "00008067": "PC", "00808665": "PVA", "00658365": "ASA", "42564f48": "BVOH",
                    "00455641": "EVA", "48495053": "HIPS", "00005050": "PP", "00505041": "PPA", "00505053": "PPS"}
ELEGOO_SUBTYPES = {
    "0000": "PLA", "0001": "PLA+", "0002": "PLA PRO", "0003": "PLA Silk", "0004": "PLA-CF", "0005": "PLA-CF",
    "0006": "PLA Matte", "0007": "PLA Glow", "0008": "PLA Wood", "0009": "PLA Basic", "000a": "Rapid PLA+",
    "000b": "PLA Marble", "000c": "PLA Galaxy", "000d": "PLA", "000e": "PLA Sparkle",
    "0100": "PETG", "0101": "PETG-CF", "0102": "PETG-GF", "0103": "PETG PRO", "0104": "PETG Translucent",
    "0105": "Rapid PETG", "0200": "ABS", "0201": "ABS", "0300": "TPU", "0301": "TPU 95A", "0302": "Rapid TPU 95A",
    "0400": "PAHT", "0401": "PAHT-CF", "0403": "PAHT-CF", "0600": "PC", "0602": "PC-FR", "0800": "ASA",
}


def load_profiles(directory: Path) -> dict:
    profiles = {}
    for path in directory.rglob("*.json"):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if isinstance(data, dict) and "name" in data:
            profiles[data["name"]] = data
    return profiles


def resolve(profiles: dict, name: str, depth: int = 0) -> dict:
    data = profiles.get(name)
    if data is None or depth > 20:
        return {}
    merged = resolve(profiles, data["inherits"], depth + 1) if data.get("inherits") else {}
    merged.update(data)
    return merged


def first(value, default=None):
    return value[0] if isinstance(value, list) and value else (value if value is not None else default)


def match(table, name):
    for pattern, value in table:
        if re.search(pattern, name):
            return value
    raise ValueError(f"no rule for {name}")


def temperatures(profile: dict) -> tuple[int, int]:
    return (int(first(profile.get("nozzle_temperature_range_low"), 190)),
            int(first(profile.get("nozzle_temperature_range_high"), 240)))


def vendor_filaments(profiles: dict, brand: str) -> dict:
    """Per filament name, the resolved profile whose nozzle range reaches highest.

    Base profiles in some vendor sets understate temperatures that every
    printer variant raises, so the widest-reaching variant stands for the
    filament."""
    chosen = {}
    for name in sorted(profiles):
        if not name.startswith(brand + " ") or profiles[name].get("type") != "filament":
            continue
        base = name.split(" @")[0].strip()
        if base in SKIP:
            continue
        profile = resolve(profiles, name)
        if base not in chosen or temperatures(profile)[::-1] > temperatures(chosen[base])[::-1]:
            chosen[base] = profile
    return chosen


def build(args) -> dict:
    qidi = json.loads(args.qidi_database.read_text(encoding="utf-8"))
    previous = read_catalog()
    used = {entry["filament_id"] for entry in qidi.values()}
    filaments = {}
    sources = {"Anycubic": args.orca_profiles / "Anycubic/filament", "Elegoo": args.elegoo_profiles / "Elegoo/filament"}
    for brand, letter in BRANDS.items():
        found = vendor_filaments(load_profiles(sources[brand]), brand)
        taken = {f["entry"]["filament_id"] for n, f in previous["filaments"].items() if n.startswith(brand + " ")}
        free = (f"QF{letter}{i:02d}" for i in range(100) if f"QF{letter}{i:02d}" not in taken | used)
        for name in sorted(found):
            profile = found[name]
            material = name[len(brand) + 1:]
            low, high = temperatures(profile)
            entry = copy.deepcopy(qidi[match(TEMPLATES, material)])
            entry.update(type=match(TYPES, material), filament_vendor=brand, nozzle_temperature=[low, high])
            if re.search("PVA", material):
                entry["filament_is_support"] = "1"
            old = previous["filaments"].get(name)
            entry["filament_id"] = old["entry"]["filament_id"] if old else next(free)
            nozzles = [n for n in NOZZLES if not (n == "0.2" and NOT_02.search(material))
                       and not (n == "0.8" and NOT_08.search(material))]
            filaments[name] = {"nozzles": nozzles, "entry": dict(sorted(entry.items()))}
    for name, old in previous["filaments"].items():
        if name not in filaments:
            raise ValueError(f"{name} ({old['entry']['filament_id']}) left its vendor's profiles; "
                             "keep it or retire its ID deliberately")
    ids = [f["entry"]["filament_id"] for f in filaments.values()]
    if len(ids) != len(set(ids)) or set(ids) & used:
        raise ValueError("filament ID collision")
    return {
        "schema": 1,
        "sources": {"Anycubic": "OrcaSlicer resources/profiles/Anycubic/filament",
                    "Elegoo": "ElegooSlicer resources/profiles/Elegoo/filament",
                    "fields": "QIDI filament-0.4.json entry for the same kind of material",
                    "elegoo_codes": "Savion/elegoo-rfid-editor src/lib/materials.ts (MIT)"},
        "elegoo_materials": ELEGOO_MATERIALS,
        "elegoo_subtypes": ELEGOO_SUBTYPES,
        "filaments": dict(sorted(filaments.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--orca-profiles", type=Path, required=True)
    parser.add_argument("--elegoo-profiles", type=Path, required=True)
    parser.add_argument("--qidi-database", type=Path, required=True)
    args = parser.parse_args()
    try:
        catalog = build(args)
    except (OSError, ValueError, KeyError) as error:
        print(f"Catalog generation failed: {error}", file=sys.stderr)
        return 1
    OUTPUT.write_text(HEADER + json.dumps(catalog, indent=1, ensure_ascii=False) + "\n" + FOOTER, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(catalog['filaments'])} filaments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
