# TigerTag aspects worth trying as a filament-name suffix, with the word QIDI's and vendors' names use.
TIGERTAG_ASPECTS = {"Silk": "Silk", "Matt": "Matte", "Translucent": "Translucent", "Wood": "Wood",
                    "Marble": "Marble", "Glow in the Dark": "Glow", "Metal": "Metal", "Satin": "Satin"}
