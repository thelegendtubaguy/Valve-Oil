BRAND_ALIASES = {"bambu lab": "Bambu", "qidi tech": "QIDI"}


def tigertag_tables(directory: Path) -> dict:
    load = lambda name: json.loads((directory / name).read_text(encoding="utf-8"))
    return {
        "tigertag_brands": {str(b["id"]): b["name"] for b in load("id_brand.json")},
        "tigertag_materials": {str(m["id"]): [m["label"], m["material_type"]] for m in load("id_material.json")
                               if m.get("product_type_id") == 142 and m.get("material_type") not in (None, "None")},
        "tigertag_aspects": {str(a["id"]): TIGERTAG_ASPECTS[a["label"]] for a in load("id_aspect.json")
                             if a["label"] in TIGERTAG_ASPECTS},
    }


def load_profiles(directory: Path) -> dict:
    profiles = {}
    for path in directory.rglob("*.json"):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if isinstance(data, dict) and "name" in data:
            profiles[data["name"]] = data
    return profiles


def resolve(profiles: dict, name: str, depth: int = 0) -> dict:
    data = profiles.get(name)
    if data is None or depth > 20:
        return {}
    merged = resolve(profiles, data["inherits"], depth + 1) if data.get("inherits") else {}
    merged.update(data)
    return merged


def first(value, default=None):
    return value[0] if isinstance(value, list) and value else (value if value is not None else default)


def match(table, name):
    for pattern, value in table:
        if re.search(pattern, name):
            return value
    raise ValueError(f"no rule for {name}")


def temperatures(profile: dict) -> tuple[int, int]:
    return (int(first(profile.get("nozzle_temperature_range_low"), 190)),
            int(first(profile.get("nozzle_temperature_range_high"), 240)))


def vendor_filaments(profiles: dict, brand: str) -> dict:
    """Per filament name, the resolved profile whose nozzle range reaches highest.

    Base profiles in some vendor sets understate temperatures that every
    printer variant raises, so the widest-reaching variant stands for the
    filament."""
    chosen, other_diameter = {}, set()
    for name in sorted(profiles):
        if profiles[name].get("type") != "filament":
            continue
        base = name.split(" @")[0].strip()
        profile = resolve(profiles, name)
        if brand in BY_VENDOR:
            if first(profile.get("filament_vendor")) != brand or profiles[name].get("instantiation") == "false":
                continue
            base = base if base.startswith(brand + " ") else f"{brand} {base}"
        elif not name.startswith(brand + " "):
            continue
        if base in SKIP:
            continue
        if float(first(profile.get("filament_diameter"), 1.75)) != 1.75:
            other_diameter.add(base)  # QIDI printers take 1.75 mm filament only
        if base not in chosen or temperatures(profile)[::-1] > temperatures(chosen[base])[::-1]:
            chosen[base] = profile
    return {base: profile for base, profile in chosen.items() if base not in other_diameter}


def build(args) -> dict:
    qidi = json.loads(args.qidi_database.read_text(encoding="utf-8"))
    previous = read_catalog()
    used = {entry["filament_id"] for entry in qidi.values()}
    filaments = {}
    sources = {"Anycubic": args.orca_profiles and args.orca_profiles / "Anycubic/filament",
               "Elegoo": args.elegoo_profiles and args.elegoo_profiles / "Elegoo/filament",
               "Bambu": args.bambu_profiles and args.bambu_profiles / "BBL/filament",
               "Creality": args.orca_profiles and args.orca_profiles / "Creality/filament"}
    bambu_ids = {} if args.only in (None, "Bambu") else dict(previous.get("bambu_ids", {}))
    for brand, letter in BRANDS.items():
        if args.only is not None and brand != args.only:
            # Kept as they are; their IDs stay taken.
            filaments.update({n: f for n, f in previous["filaments"].items() if f["entry"]["filament_vendor"] == brand})
            continue
        if sources[brand] is None:
            raise ValueError(f"{brand} needs its slicer profiles")
        found = vendor_filaments(load_profiles(sources[brand]), brand)
        taken = {f["entry"]["filament_id"] for n, f in previous["filaments"].items() if n.startswith(brand + " ")}
        free = (f"QF{letter}{i:02d}" for i in range(100) if f"QF{letter}{i:02d}" not in taken | used)
        for name in sorted(found):
            profile = found[name]
            if brand == "Bambu":
                bambu_id = first(profile["filament_id"])
                if bambu_id in bambu_ids:
                    raise ValueError(f"{name} and {bambu_ids[bambu_id]} share Bambu Lab ID {bambu_id}")
                bambu_ids[bambu_id] = name
            if name in qidi:
                continue  # QIDI's own entry, such as Bambu ABS, stands for it
            material = name[len(brand) + 1:]
            if brand in BY_VENDOR:
                material = f"{first(profile.get('filament_type'), '')} {material}"  # CR-Nylon is a PA
            low, high = temperatures(profile)
            entry = copy.deepcopy(qidi[match(TEMPLATES, material)])
            entry.update(type=match(TYPES, material), filament_vendor=brand, nozzle_temperature=[low, high])
            if re.search("PVA|Support", material):
                entry["filament_is_support"] = "1"
            old = previous["filaments"].get(name)
            entry["filament_id"] = old["entry"]["filament_id"] if old else next(free)
            nozzles = [n for n in NOZZLES if not (n == "0.2" and NOT_02.search(material))
                       and not (n == "0.8" and NOT_08.search(material))]
            filaments[name] = {"nozzles": nozzles, "entry": dict(sorted(entry.items()))}
    for name, old in previous["filaments"].items():
        if name not in filaments and (args.only is None or old["entry"]["filament_vendor"] == args.only):
            raise ValueError(f"{name} ({old['entry']['filament_id']}) left its vendor's profiles; "
                             "keep it or retire its ID deliberately")
    ids = [f["entry"]["filament_id"] for f in filaments.values()]
    if len(ids) != len(set(ids)) or set(ids) & used:
        raise ValueError("filament ID collision")
    tigertag = (tigertag_tables(args.tigertag_database) if args.tigertag_database else
                {key: previous[key] for key in ("tigertag_brands", "tigertag_materials", "tigertag_aspects")})
    return {
        "schema": 1,
        "sources": {"Anycubic": "OrcaSlicer resources/profiles/Anycubic/filament",
                    "Elegoo": "ElegooSlicer resources/profiles/Elegoo/filament",
                    "Bambu": "BambuStudio resources/profiles/BBL/filament",
                    "Creality": "OrcaSlicer resources/profiles/Creality/filament, filament_vendor Creality",
                    "fields": "QIDI filament-0.4.json entry for the same kind of material",
                    "elegoo_codes": "Savion/elegoo-rfid-editor src/lib/materials.ts (MIT)",
                    "creality_codes": "Creality's tag-writer material table",
                    "tigertag_codes": "TigerTag-Project/TigerTag-RFID-Guide database/ (CC0)"},
        "brand_aliases": BRAND_ALIASES,
        "elegoo_materials": ELEGOO_MATERIALS,
        "elegoo_subtypes": ELEGOO_SUBTYPES,
        "bambu_ids": dict(sorted(bambu_ids.items())),
        "creality_materials": CREALITY_MATERIALS,
        **tigertag,
        "filaments": dict(sorted(filaments.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--orca-profiles", type=Path)
    parser.add_argument("--elegoo-profiles", type=Path)
    parser.add_argument("--bambu-profiles", type=Path)
    parser.add_argument("--qidi-database", type=Path, required=True)
    parser.add_argument("--only", choices=sorted(BRANDS))
    parser.add_argument("--tigertag-database", type=Path)
    args = parser.parse_args()
    try:
        catalog = build(args)
    except (OSError, ValueError, KeyError) as error:
        print(f"Catalog generation failed: {error}", file=sys.stderr)
        return 1
    OUTPUT.write_text(HEADER + json.dumps(catalog, indent=1, ensure_ascii=False) + "\n" + FOOTER, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(catalog['filaments'])} filaments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
