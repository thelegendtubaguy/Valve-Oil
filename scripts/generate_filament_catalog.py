#!/usr/bin/env python3
"""Regenerate installer/klipper/extras/filament_catalog.py.

Maintainer tool. It builds QIDI filament-database entries for Anycubic,
Elegoo, Bambu Lab, and Creality filaments from the vendors' slicer profiles
(OrcaSlicer's Anycubic and Creality profiles, ElegooSlicer's Elegoo profiles,
BambuStudio's Bambu Lab profiles) and QIDI's stock 0.4 mm database:

- names, material types, and nozzle temperature ranges come from each
  vendor's profiles (the range of the variant that reaches highest);
- the remaining QIDI fields (Box heater range, chamber, drying) come from the
  QIDI entry for the same kind of material;
- IDs are ``QFX`` (Anycubic), ``QFY`` (Elegoo), ``QFZ`` (Bambu Lab), and
  ``QFW`` (Creality) plus two digits. An ID already in the catalog is never changed, because Box slots
  carry it;
- Bambu Lab's own filament IDs (``GFA00``), which Bambu tags carry, map to
  filament names, including those QIDI's database already has (Bambu ABS),
  which the catalog leaves out;
- Creality's filaments are the Creality profiles whose filament_vendor is
  Creality (CR-PLA, Hyper PLA, ...), named "Creality <profile name>". Their
  QIDI fields follow the profile's filament_type with its name;
- tag code tables: Creality's material codes (CREALITY_MATERIALS) and
  TigerTag's brand, material, and aspect IDs from a checkout of
  TigerTag-Project/TigerTag-RFID-Guide's database/ (CC0).

``--only <brand>`` rebuilds one vendor's filaments and keeps every other
vendor's entries as they are; ``--tigertag-database`` refreshes the TigerTag
tables (kept from the previous catalog when not given).

Usage:
  generate_filament_catalog.py --orca-profiles <OrcaSlicer>/resources/profiles \\
      --elegoo-profiles <ElegooSlicer>/resources/profiles \\
      --bambu-profiles <BambuStudio>/resources/profiles \\
      --qidi-database <filament_config>/filament-0.4.json \\
      [--only Creality] [--tigertag-database <TigerTag-RFID-Guide>/database]
"""
